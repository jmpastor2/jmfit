export const EXERCISES: readonly Exercise[] = DEFS.map(def)

const BY_ID = new Map(EXERCISES.map((e) => [e.id, e]))

export function exerciseById(id: string): Exercise | undefined {
  return BY_ID.get(id)
}

/** Lowercase and strip diacritics so "jalon" matches "Jalón". */
export function normalize(s: string): string {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim()
}

const SEARCH_INDEX = EXERCISES.map((e) => ({
  e,
  name: normalize(e.name),
  terms: [e.name, ...(e.aliases ?? [])].map(normalize),
}))

/**
 * Accent-insensitive search by name and aliases. Every query word must appear in some term.
 * Results: name prefix matches first, then name matches, then alias matches.
 */
export function searchExercises(query: string): Exercise[] {
  const q = normalize(query)
  if (!q) return [...EXERCISES]
  const words = q.split(/\s+/)
  const scored: { e: Exercise; score: number }[] = []
  for (const { e, name, terms } of SEARCH_INDEX) {
    const hit = terms.some((t) => words.every((w) => t.includes(w)))
    if (!hit) continue
    const score = name.startsWith(q) ? 0 : words.every((w) => name.includes(w)) ? 1 : 2
    scored.push({ e, score })
  }
  return scored
    .sort(
      (a, b) =>
        a.score - b.score ||
        a.e.name.length - b.e.name.length ||
        a.e.name.localeCompare(b.e.name, 'es'),
    )
    .map((s) => s.e)
}
